    # positive fixtures
    # ------------------------------------------------------------------

    def test_original_third_party_passes(self):
        catalog = _catalog(_record("asset_kenney_ui_pack_v2"))
        result = self._run(catalog)
        self.assertEqual(result["status"], "PASS")
        self.assertEqual(result["findings_count"], 0)

