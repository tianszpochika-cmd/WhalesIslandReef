    def test_cross_check_approval_with_valid_lineage_passes(self):
        catalog = _catalog(
            _record("asset_kenney_ui_pack_v2"),
            _record(
                "asset_ui_icon_derived",
                origin_kind="derived",
                parent_asset_id="asset_kenney_ui_pack_v2",
                conversion_steps=["retint"],
                third_party_claim=None,
                license_basis=_lic(),
            ),
        )
        lineage_result = validate_lineage_catalog(catalog, self.root.resolve())
        asset_records = [
            {"canonical_asset_id": "asset_ui_icon_derived", "state": "IntakeEligible"},
            {"canonical_asset_id": "asset_kenney_ui_pack_v2", "state": "Candidate"},
        ]
        cross = cross_check_asset_records(catalog, asset_records, lineage_result)
        self.assertEqual(cross["approval_records_checked"], 1)
        self.assertEqual(cross["violations"], 0)

