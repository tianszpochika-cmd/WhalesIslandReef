"""Unit tests for the D18-L38 generated asset guard (read-only lineage guard).

Positive fixtures (must stay PASS):
- third-party CC0 original with third_party_claim
- converted asset with parent + steps, same license
- derived asset with parent + steps, license basis preserved
- project-authored generated asset (no parent, PROJECT-OWNED basis)
- generated asset derived from an original with lineage
- external parent with source URL + on-disk evidence
- multi-hop chain original -> converted -> derived
- cross-check: approval-state record with valid lineage

Negative fixtures (must be BLOCKED, each asserts its rule):
- derived without parent / converted without steps (missing lineage blocks)
- original with parent, original without third-party claim
- generated masquerading as third-party original
- non-original declaring third_party_claim
- license/rights widening, self parent, circular lineage
- unknown parent without external evidence, duplicate ids
- bad asset id, unknown origin kind, evidence path escape
- cross-check: approval-state record with invalid lineage

The tool must never modify any input file (read-only contract) and must not
create or alter textures, models or binaries.
"""

import json
import tempfile
import unittest
from pathlib import Path

from tools.d18_generated_asset_guard import (
    validate_lineage_catalog,
    cross_check_asset_records,
)


def _record(asset_id: str, **overrides: object) -> dict:
    base = {
        "canonical_asset_id": asset_id,
        "origin_kind": "original",
        "parent_asset_id": None,
        "conversion_steps": None,
        "project_authored": None,
        "third_party_claim": {
            "source_id": "source_kenney",
            "source_url": "https://kenney.nl/assets/ui-pack",
            "license_id": "CC0-1.0",
        },
        "license_basis": None,
        "evidence_paths": [],
        "external_parent": None,
    }
    base.update(overrides)
    return base


def _catalog(*records: dict) -> dict:
    return {"lineage_kind": "d18_generated_asset_lineage", "schema_version": 1, "records": list(records)}


def _lic(attribution: bool = False, **overrides: object) -> dict:
    basis = {
        "license_id": "CC0-1.0",
        "attribution_required": attribution,
        "commercial_use": True,
        "modification_allowed": True,
        "distribution_with_game": True,
    }
    basis.update(overrides)
    return basis


class GeneratedAssetGuardTests(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)
        (self.root / "evidence").mkdir(parents=True, exist_ok=True)
        (self.root / "evidence" / "license.txt").write_text("CC0-1.0\n", encoding="utf-8")

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def _run(self, catalog: dict) -> dict:
        return validate_lineage_catalog(catalog, self.root.resolve())

