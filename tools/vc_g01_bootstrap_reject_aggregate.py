"""Aggregate the three independent VC-G01 bootstrap-reject Player runs.

The source summaries are generated by the real Win32 Player harness.  This
utility only reads those summaries and writes a scoped evidence record; it
does not infer missing targets or promote VC-G01's formal status.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RESULT_DIR = ROOT / "game/tools/results/VISUAL-CLEAN/VC-G01"
TARGETS = ("I", "M", "T")


def load_target(target: str) -> dict:
    path = RESULT_DIR / f"VC_G01_BOOTSTRAP_REJECT_{target}_20260906.json"
    if not path.is_file():
        raise FileNotFoundError(f"missing bootstrap target summary: {path}")
    with path.open("r", encoding="utf-8-sig") as stream:
        summary = json.load(stream)
    matrix = summary.get("bootstrap_reject_matrix") or {}
    if matrix.get("target_key") != target:
        raise ValueError(f"{target}: target_key mismatch: {matrix.get('target_key')!r}")
    if not matrix.get("target_proof"):
        raise ValueError(f"{target}: target_proof is not true")
    return summary


def build_record() -> dict:
    summaries = {target: load_target(target) for target in TARGETS}
    targets = {}
    for target, summary in summaries.items():
        matrix = summary["bootstrap_reject_matrix"]
        detail = matrix[{"I": "warehouse", "M": "market", "T": "tavern"}[target]]
        step = next(
            step
            for step in summary["input_steps"]
            if step.get("name")
            == {
                "I": "bootstrap_warehouse_i",
                "M": "bootstrap_market_m",
                "T": "bootstrap_tavern_t",
            }[target]
        )
        targets[target] = {
            "summary": f"game/tools/results/VISUAL-CLEAN/VC-G01/VC_G01_BOOTSTRAP_REJECT_{target}_20260906.json",
            "probe": f"game/tools/results/D19/D19-R03-A01/D19_R03_A01_RUNTIME_ROUTE_PROBE_BOOTSTRAP_REJECT_{target}_20260906.json",
            "player_log": f"game/tools/results/VISUAL-CLEAN/VC-G01/VC_G01_PLAYER_RUNTIME_BOOTSTRAP_REJECT_{target}_20260906.log",
            "player_started": bool(
                next(
                    item
                    for item in summary["input_steps"]
                    if item.get("name") == "player_started"
                ).get("succeeded")
            ),
            "scene_marker_seen": bool(summary.get("scene_marker_seen")),
            "input_step_succeeded": bool(detail.get("input_step_succeeded")),
            "send_input_accepted": bool(step.get("send_input_accepted")),
            "unready_owner_edge_count": int(detail.get("unready_owner_edge_count", 0)),
            "reject_log_found_after_marker": bool(
                detail.get("reject_log_found_after_marker")
            ),
            "page_open_transition_count": int(
                detail.get("page_open_transition_count", 0)
            ),
            "player_log_archive_exists": bool(summary.get("player_log_archive_exists")),
            "target_proof": bool(matrix.get("target_proof")),
        }

    return {
        "schema": "VC_G01_RUNTIME_BOOTSTRAP_REJECT_MATRIX_V1",
        "task_id": "VC-G01",
        "status": "PASS_WITHIN_SCOPE",
        "evidence_mode": (
            "three independent standalone Player runs using real native Win32 "
            "SendInput; D19 probe remained read-only"
        ),
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "targets": targets,
        "matrix_proof": all(item["target_proof"] for item in targets.values()),
        "formal_status_unchanged": {
            "vc_g01": "IN_PROGRESS",
            "reason": (
                "This record closes the owner-not-ready reject evidence for I/M/T "
                "within the bootstrap-window scope. It does not replace the full "
                "movement/page matrix, manual physical-input acceptance, or the "
                "formal VC-G01 gate."
            ),
        },
        "scope_boundary": (
            "Each target requires a real accepted key step, a same-frame probe "
            "owner=false state, the target page still hidden, a D29 reject log "
            "after the unique run marker, and zero page-open transitions."
        ),
    }


def main() -> None:
    output = RESULT_DIR / "VC_G01_BOOTSTRAP_REJECT_MATRIX_20260906.json"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(build_record(), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(output)


if __name__ == "__main__":
    main()
